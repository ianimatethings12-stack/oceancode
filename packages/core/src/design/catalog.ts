function makeArchetype(
  id: string,
  name: string,
  category: DesignCategory,
  vibe: string,
  primary: string,
  secondary: string,
  accent: string,
  background: string,
  surface: string,
  text: string,
  textMuted: string,
  border: string,
  fontSans: string,
  fontMono: string,
  headingStyle: string,
  keywords: readonly string[],
  button: string,
  card: string,
  input: string,
  navigation: string,
): DesignArchetype {
  return {
    id,
    name,
    category,
    vibe,
    palette: { primary, secondary, accent, background, surface, text, textMuted, border },
    typography: { fontSans, fontMono, headingStyle },
    keywords,
    cssVariables: {
      "--color-primary": primary,
      "--color-secondary": secondary,
      "--color-accent": accent,
      "--color-bg": background,
      "--color-surface": surface,
      "--color-text": text,
      "--color-text-muted": textMuted,
      "--color-border": border,
      "--font-sans": fontSans,
      "--font-mono": fontMono,
    },
    componentPatterns: { button, card, input, navigation },
  }
}

